// Generates src/protocol.gen.ts from protocol/protocol.schema.json. Run via `just gen`.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../../protocol/protocol.schema.json");
const outPath = resolve(here, "../src/protocol.gen.ts");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const ts = await compile(schema, "ProtocolMessage", {
  bannerComment: "// GENERATED by `just gen` from protocol/protocol.schema.json — DO NOT EDIT.",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: false,
});
await writeFile(outPath, ts);
console.log(`wrote ${outPath}`);
